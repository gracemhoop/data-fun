            summary = pd.DataFrame([{"Check": h["Check"], "Count": h["Count"]} for h in hits])
            row = drilldown(summary, "upid_fmt", "Click a check to see the offending rows.")
            if row is not None:
                chosen = next(h for h in hits if h["Check"] == row["Check"])
                res    = df[chosen["_mask"]].reset_index(drop=True)
                st.markdown(f"#### {chosen['Check']} — {len(res):,} rows")
                st.dataframe(res, use_container_width=True)
            if all(h["Count"] == 0 for h in hits):
                st.success("✅ All UPID values pass format validation.")
