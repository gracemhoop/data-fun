    # ── UPID format validation ────────────────────────────────────────────────
    st.markdown("---")
    st.markdown("**UPID Format Validation**")
    st.caption("Validate that member IDs conform to the vendor-specified format (length, character type, prefix/suffix).")
    upid_fmt_col = st.selectbox("UPID column to validate", cols, key="upid_fmt_col")
    fa, fb, fc_  = st.columns(3)
    upid_exp_len = fa.number_input("Expected exact length (0 = skip)", min_value=0, value=0, key="upid_exp_len")
    upid_regex   = fb.text_input("Regex pattern (leave blank to skip)", placeholder=r"^\d{9}$", key="upid_regex")
    upid_max_len = fc_.number_input("Maximum allowed length (0 = skip)", min_value=0, value=0, key="upid_max_len")

    if st.button("Validate format", key="btn_upid_fmt"):
        s    = df[upid_fmt_col].astype(str).str.strip()
        hits = []

        if upid_exp_len > 0:
            wrong_len = s[(s != "") & (s.str.len() != upid_exp_len)]
            cnt = len(wrong_len)
            hits.append({"Check": f"Length ≠ {upid_exp_len}", "Count": cnt,
                         "_mask": ((s != "") & (s.str.len() != upid_exp_len)).values})

        if upid_max_len > 0:
            over_max = s[s.str.len() > upid_max_len]
            hits.append({"Check": f"Length > {upid_max_len}", "Count": len(over_max),
                         "_mask": (s.str.len() > upid_max_len).values})

        if upid_regex.strip():
            try:
                pattern  = re.compile(upid_regex.strip())
                no_match = s[(s != "") & ~s.str.fullmatch(upid_regex.strip())]
                hits.append({"Check": f"Does not match `{upid_regex.strip()}`", "Count": len(no_match),
                             "_mask": ((s != "") & ~s.str.fullmatch(upid_regex.strip())).values})
            except re.error as e:
                st.error(f"Invalid regex: {e}")

