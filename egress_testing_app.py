@st.cache_data
def load_file(data, sep, skip, nq):
    kw = {"dtype": str, "keep_default_na": False, "na_values": [],
          "skipinitialspace": skip, "sep": sep}
    if nq:
        kw["quoting"] = 3
    return pd.read_csv(io.BytesIO(data), **kw)


